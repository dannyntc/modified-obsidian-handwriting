const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const vm = require('node:vm');
const mainPath = process.argv[2] || path.join(__dirname, '..', 'main.js');
const stylesPath = process.argv[3] || path.join(path.dirname(mainPath), 'styles.css');
const main = fs.readFileSync(mainPath, 'utf8');
const styles = fs.readFileSync(stylesPath, 'utf8');
const startMarker = 'xt=class{constructor(';
const endMarker = ';var Fb=';
const start = main.indexOf(startMarker);
const end = main.indexOf(endMarker, start);
assert.ok(start >= 0 && end > start, 'MobileTools toolbar class is missing');
const toolbar = main.slice(start, end);
const hash = crypto.createHash('sha256').update(toolbar).digest('hex');
assert.equal(hash, '90e9dc88f4d8e85c29d7a3285032449c186e61b08c12109cd6b8073fd4a42199', 'toolbar class differs from b94347b');
assert.match(main, /HandwritingSvgRecoveryManager/);
assert.match(main, /corner=\"top-right\"/);
assert.match(main, /selectionStyleTabsFor\(e\)/);
assert.match(main, /armDrag\(e\)/);
assert.doesNotMatch(main, /mountHeaderToolbar/);
assert.doesNotMatch(main, /handwriting-header-tools/);
assert.doesNotMatch(styles, /handwriting-header-tools/);
new vm.Script(main, { filename: mainPath });
console.log('PASS: restored toolbar matches b94347b and SVG recovery remains present');
